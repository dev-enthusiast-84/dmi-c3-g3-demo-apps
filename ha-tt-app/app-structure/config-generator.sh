#!/bin/bash
# ============================================
# Configuration Generator Script
# ============================================
# PURPOSE: Generate configuration files and user data scripts
# SCOPE: Standalone utility for configuration management

set -e

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
OUTPUT_DIR="${SCRIPT_DIR}/generated"

print_header() {
  echo ""
  echo "╔════════════════════════════════════════════════════════════════╗"
  echo "║        Configuration Generator - Hit Counter App              ║"
  echo "╚════════════════════════════════════════════════════════════════╝"
  echo ""
}

print_menu() {
  echo "What would you like to generate?"
  echo ""
  echo "  1) .env file (for local development)"
  echo "  2) User data script (for EC2 deployment)"
  echo "  3) Complete configuration package"
  echo "  4) Environment variables only"
  echo ""
  echo "  Q) Quit"
  echo ""
}

prompt_for_values() {
  echo "Enter your configuration values:"
  echo ""

  read -p "Database Type (postgres/mysql) [postgres]: " DB_TYPE
  DB_TYPE="${DB_TYPE:-postgres}"

  read -p "Database Endpoint (e.g., mydb.xxxxx.rds.amazonaws.com): " DB_ENDPOINT
  if [ -z "$DB_ENDPOINT" ]; then
    echo "✗ Database endpoint is required"
    return 1
  fi

  read -p "Database User (e.g., postgres/admin): " DB_USER
  if [ -z "$DB_USER" ]; then
    echo "✗ Database user is required"
    return 1
  fi

  read -sp "Database Password: " DB_PASSWORD
  echo ""
  if [ -z "$DB_PASSWORD" ]; then
    echo "✗ Database password is required"
    return 1
  fi

  read -p "Database Name [ha-tt-db]: " DB_NAME
  DB_NAME="${DB_NAME:-ha-tt-db}"

  if [ "$DB_TYPE" = "postgres" ]; then
    read -p "Database Port [5432]: " DB_PORT
    DB_PORT="${DB_PORT:-5432}"
  else
    read -p "Database Port [3306]: " DB_PORT
    DB_PORT="${DB_PORT:-3306}"
  fi

  read -p "Application Port [8000]: " APP_PORT
  APP_PORT="${APP_PORT:-8000}"

  read -p "Application Directory [/opt/app]: " APP_DIR
  APP_DIR="${APP_DIR:-/opt/app}"

  echo ""
  return 0
}

generate_env_file() {
  local output_file="$1"

  cat > "$output_file" <<EOF
# Application Configuration
NODE_ENV=production
APP_PORT=$APP_PORT

# Database Configuration
DB_TYPE=$DB_TYPE
DB_ENDPOINT=$DB_ENDPOINT
DB_USER=$DB_USER
DB_PASSWORD=$DB_PASSWORD
DB_NAME=$DB_NAME
DB_PORT=$DB_PORT
EOF

  echo "✓ .env file generated: $output_file"
}

generate_env_vars() {
  cat <<EOF
# Export these to your shell
export DB_TYPE="$DB_TYPE"
export DB_ENDPOINT="$DB_ENDPOINT"
export DB_USER="$DB_USER"
export DB_PASSWORD="$DB_PASSWORD"
export DB_NAME="$DB_NAME"
export DB_PORT="$DB_PORT"
export APP_PORT="$APP_PORT"
EOF
}

generate_user_data_script() {
  local output_file="$1"

  cat > "$output_file" <<'SCRIPT_START'
#!/bin/bash
# EC2 User Data Script - Web Server Setup
# Generated by config-generator.sh
# Customize the database configuration variables below

set -e
exec > >(tee /var/log/user-data.log)
exec 2>&1

# ============================================
# CONFIGURATION
# ============================================
SCRIPT_START

  cat >> "$output_file" <<SCRIPT_CONFIG
DB_TYPE="$DB_TYPE"
DB_ENDPOINT="$DB_ENDPOINT"
DB_USER="$DB_USER"
DB_PASSWORD="$DB_PASSWORD"
DB_NAME="$DB_NAME"
DB_PORT="$DB_PORT"
APP_PORT=$APP_PORT
APP_DIR="/opt/app"
SCRIPT_CONFIG

  cat >> "$output_file" <<'SCRIPT_END'

echo "=== EC2 User Data Script - Web Server Setup ==="
echo "Configuration:"
echo "  Database Type: $DB_TYPE"
echo "  Database Endpoint: $DB_ENDPOINT"
echo "  App Directory: $APP_DIR"
echo "  App Port: $APP_PORT"
date

# ============================================
# SECTION 1: System Setup
# ============================================
echo "=== Section 1: System Setup ==="

echo "Updating system packages..."
apt-get update
apt-get upgrade -y

echo "Installing Node.js 20.x..."
curl -fsSL https://deb.nodesource.com/setup_20.x | sudo -E bash -
apt-get install -y nodejs

echo "Installing Nginx..."
apt-get install -y nginx
systemctl enable nginx

echo "✓ System setup complete"

# ============================================
# SECTION 2: Application Deployment
# ============================================
echo "=== Section 2: Application Deployment ==="

echo "Creating application directory: $APP_DIR"
mkdir -p $APP_DIR
cd $APP_DIR

# Deploy from embedded application code
echo "Deploying application code..."

cat > package.json <<'PACKAGE_EOF'
{
  "name": "hit-counter-app",
  "version": "2.0.0",
  "description": "Hit counter application with database integration",
  "main": "index.js",
  "scripts": {
    "start": "node index.js"
  },
  "dependencies": {
    "express": "^4.18.2",
    "pg": "^8.11.3",
    "mysql2": "^3.6.5",
    "dotenv": "^16.3.1"
  }
}
PACKAGE_EOF

cat > index.js <<'APP_EOF'
const express = require('express');
const { Pool } = require('pg');
const mysql = require('mysql2/promise');
require('dotenv').config();

const app = express();
const port = process.env.APP_PORT || 8000;
const dbType = process.env.DB_TYPE || 'postgres';

let pool;

const dbConfig = {
  host: process.env.DB_ENDPOINT || 'localhost',
  user: process.env.DB_USER || 'postgres',
  password: process.env.DB_PASSWORD,
  database: process.env.DB_NAME || 'ha-tt-db',
  port: parseInt(process.env.DB_PORT || '5432')
};

async function initializeDatabase() {
  try {
    if (dbType === 'postgres') {
      pool = new Pool(dbConfig);
      console.log('PostgreSQL pool created');
    } else {
      pool = mysql.createPool(dbConfig);
      console.log('MySQL pool created');
    }
  } catch (error) {
    console.error('Database pool error:', error.message);
    process.exit(1);
  }
}

async function createTableIfNotExists() {
  try {
    if (dbType === 'postgres') {
      const client = await pool.connect();
      await client.query(`
        CREATE TABLE IF NOT EXISTS hits (
          id SERIAL PRIMARY KEY,
          hit_count INT DEFAULT 0,
          last_hit TIMESTAMP DEFAULT CURRENT_TIMESTAMP
        )
      `);
      client.release();
    } else {
      const conn = await pool.getConnection();
      await conn.execute(`
        CREATE TABLE IF NOT EXISTS hits (
          id INT AUTO_INCREMENT PRIMARY KEY,
          hit_count INT DEFAULT 0,
          last_hit TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
        )
      `);
      conn.release();
    }
    console.log('Hits table ready');
  } catch (error) {
    console.error('Table creation error:', error.message);
    process.exit(1);
  }
}

async function initializeCounter() {
  try {
    if (dbType === 'postgres') {
      const client = await pool.connect();
      const result = await client.query('SELECT COUNT(*) as count FROM hits');
      if (parseInt(result.rows[0].count) === 0) {
        await client.query('INSERT INTO hits (hit_count) VALUES (0)');
      }
      client.release();
    } else {
      const conn = await pool.getConnection();
      const [rows] = await conn.execute('SELECT COUNT(*) as count FROM hits');
      if (rows[0].count === 0) {
        await conn.execute('INSERT INTO hits (hit_count) VALUES (0)');
      }
      conn.release();
    }
    console.log('Hit counter ready');
  } catch (error) {
    console.error('Counter initialization error:', error.message);
    process.exit(1);
  }
}

app.get('/health', async (req, res) => {
  try {
    if (dbType === 'postgres') {
      const client = await pool.connect();
      await client.query('SELECT NOW()');
      client.release();
    } else {
      const conn = await pool.getConnection();
      await conn.ping();
      conn.release();
    }
    res.json({ status: 'healthy', db: dbType });
  } catch (error) {
    res.status(503).json({ status: 'unhealthy', error: error.message });
  }
});

app.get('/', async (req, res) => {
  try {
    if (dbType === 'postgres') {
      const client = await pool.connect();
      await client.query('UPDATE hits SET hit_count = hit_count + 1, last_hit = CURRENT_TIMESTAMP WHERE id = 1');
      const result = await client.query('SELECT hit_count, last_hit FROM hits WHERE id = 1');
      client.release();
      const { hit_count, last_hit } = result.rows[0];

      res.send(`
        <!DOCTYPE html>
        <html>
          <head><meta charset="UTF-8"><meta name="viewport" content="width=device-width">
          <title>Hit Counter</title>
          <style>body{font-family:Arial;text-align:center;margin-top:50px;background:#f5f5f5}.container{background:#fff;padding:40px;border-radius:10px;width:400px;margin:0 auto;box-shadow:0 2px 10px rgba(0,0,0,.1)}.count{font-size:56px;font-weight:bold;color:#2563eb;margin:20px 0}.label{font-size:20px;color:#666}.timestamp{font-size:14px;color:#999;margin-top:30px}.status{background:#d1fae5;color:#065f46;padding:10px;border-radius:5px;margin-top:20px;font-size:12px}</style>
          </head><body><div class="container"><div class="label">Total Page Hits</div><div class="count">${hit_count}</div><div class="timestamp">Last hit: ${new Date(last_hit).toLocaleString()}</div><div class="status">✓ Connected to ${dbType}</div></div></body>
        </html>
      `);
    } else {
      const conn = await pool.getConnection();
      await conn.execute('UPDATE hits SET hit_count = hit_count + 1 WHERE id = 1');
      const [rows] = await conn.execute('SELECT hit_count, last_hit FROM hits WHERE id = 1');
      conn.release();
      const { hit_count, last_hit } = rows[0];

      res.send(`
        <!DOCTYPE html>
        <html>
          <head><meta charset="UTF-8"><meta name="viewport" content="width=device-width">
          <title>Hit Counter</title>
          <style>body{font-family:Arial;text-align:center;margin-top:50px;background:#f5f5f5}.container{background:#fff;padding:40px;border-radius:10px;width:400px;margin:0 auto;box-shadow:0 2px 10px rgba(0,0,0,.1)}.count{font-size:56px;font-weight:bold;color:#2563eb;margin:20px 0}.label{font-size:20px;color:#666}.timestamp{font-size:14px;color:#999;margin-top:30px}.status{background:#d1fae5;color:#065f46;padding:10px;border-radius:5px;margin-top:20px;font-size:12px}</style>
          </head><body><div class="container"><div class="label">Total Page Hits</div><div class="count">${hit_count}</div><div class="timestamp">Last hit: ${new Date(last_hit).toLocaleString()}</div><div class="status">✓ Connected to ${dbType}</div></div></body>
        </html>
      `);
    }
  } catch (error) {
    res.status(500).send(`<html><body style="text-align:center;margin-top:50px"><h1>Error</h1><p>${error.message}</p></body></html>`);
  }
});

async function start() {
  try {
    await initializeDatabase();
    await createTableIfNotExists();
    await initializeCounter();

    app.listen(port, () => {
      console.log(`Application listening on port ${port}`);
    });
  } catch (error) {
    console.error('Failed to start:', error.message);
    process.exit(1);
  }
}

start();
APP_EOF

cat > .env <<ENV_EOF
DB_TYPE=$DB_TYPE
DB_ENDPOINT=$DB_ENDPOINT
DB_USER=$DB_USER
DB_PASSWORD=$DB_PASSWORD
DB_NAME=$DB_NAME
DB_PORT=$DB_PORT
APP_PORT=$APP_PORT
NODE_ENV=production
ENV_EOF

echo "Installing npm dependencies..."
npm install --production

echo "✓ Application deployment complete"

# ============================================
# SECTION 3: Nginx Configuration
# ============================================
echo "=== Section 3: Nginx Configuration ==="

cat > /etc/nginx/sites-available/default <<'NGINX_EOF'
server {
    listen 80 default_server;
    listen [::]:80 default_server;
    server_name _;

    location / {
        proxy_pass http://127.0.0.1:8000;
        proxy_http_version 1.1;
        proxy_set_header Host $host;
        proxy_set_header X-Real-IP $remote_addr;
        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
    }

    location /health {
        proxy_pass http://127.0.0.1:8000/health;
        proxy_http_version 1.1;
        proxy_set_header Host $host;
    }
}
NGINX_EOF

nginx -t
systemctl reload nginx

echo "✓ Nginx configuration complete"

# ============================================
# SECTION 4: Service Setup
# ============================================
echo "=== Section 4: Service Setup ==="

cat > /etc/systemd/system/app.service <<'SERVICE_EOF'
[Unit]
Description=Hit Counter Web Application
After=network.target

[Service]
Type=simple
User=ubuntu
WorkingDirectory=/opt/app
EnvironmentFile=/opt/app/.env
ExecStart=/usr/bin/node /opt/app/index.js
Restart=always
RestartSec=10

[Install]
WantedBy=multi-user.target
SERVICE_EOF

systemctl daemon-reload
systemctl enable app

echo "✓ Service setup complete"

# ============================================
# SECTION 5: Service Startup
# ============================================
echo "=== Section 5: Starting Services ==="

systemctl start app
systemctl restart nginx

sleep 3

if systemctl is-active --quiet app; then
  echo "✓ Application service is running"
else
  echo "✗ Application service failed to start"
  systemctl status app
fi

if systemctl is-active --quiet nginx; then
  echo "✓ Nginx is running"
else
  echo "✗ Nginx failed to start"
fi

echo ""
echo "=== EC2 Setup Complete ==="
echo "Application will be available at: http://<instance-ip>"
echo "Health check: http://<instance-ip>/health"
echo "Application logs: sudo journalctl -u app -f"
echo "User data logs: /var/log/user-data.log"
SCRIPT_END

  chmod +x "$output_file"
  echo "✓ User data script generated: $output_file"
}

# Main menu loop
print_header

while true; do
  print_menu
  read -p "Select option: " choice

  case "$choice" in
    1)
      mkdir -p "$OUTPUT_DIR"
      if prompt_for_values; then
        generate_env_file "$OUTPUT_DIR/.env"
      fi
      ;;
    2)
      mkdir -p "$OUTPUT_DIR"
      if prompt_for_values; then
        generate_user_data_script "$OUTPUT_DIR/userdata-custom.sh"
      fi
      ;;
    3)
      mkdir -p "$OUTPUT_DIR"
      if prompt_for_values; then
        generate_env_file "$OUTPUT_DIR/.env"
        generate_user_data_script "$OUTPUT_DIR/userdata-custom.sh"
        generate_env_vars > "$OUTPUT_DIR/env-vars.sh"
        echo "✓ Environment variables script generated: $OUTPUT_DIR/env-vars.sh"
      fi
      ;;
    4)
      if prompt_for_values; then
        generate_env_vars
      fi
      ;;
    q|Q)
      echo "Goodbye!"
      exit 0
      ;;
    *)
      echo "✗ Invalid option. Please try again."
      ;;
  esac

  echo ""
  read -p "Press Enter to continue..."
done
